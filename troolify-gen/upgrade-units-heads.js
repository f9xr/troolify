/* ============================================================================
   Troolify - upgrade tools/units/*.html <head> to the canonical tool-page
   template used by tools/youtube, tools/video and tools/time.

   The units pages were generated by the older standalone gen-units.js template,
   which omitted: GA (gtag) scripts, the Article JSON-LD, theme-color, og:locale,
   og:image dimensions, the article:* metas and the full twitter card. Their
   <body> is already canonical, so only the <head> is replaced.

   Values are preserved from each existing page (title, meta description,
   og:description, FAQ, page <style>); name/tag/keywords come from the registry.
   ============================================================================ */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BASE = 'https://f9xr.org/troolify';
const DATE = '2026-10-10';
const CAT_FOLDER = 'units';
const CAT_NAME = 'Unit Converters';

global.window = {};
eval(fs.readFileSync(path.join(ROOT, 'assets', 'js', 'tools-data.js'), 'utf8'));
const REG = {};
(global.window.TOOLS || []).forEach(t => { REG[t.href] = t; });

const decode = (s) => String(s)
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'");

function buildJsonLd(reg, url, titleRaw, metaDescRaw, faqMain) {
  const cat = { name: CAT_NAME };
  const breadcrumb = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: BASE + '/index.html' },
      { '@type': 'ListItem', position: 2, name: 'Tools', item: BASE + '/tools/index.html' },
      { '@type': 'ListItem', position: 3, name: cat.name, item: BASE + '/tools/' + CAT_FOLDER + '/' },
      { '@type': 'ListItem', position: 4, name: reg.name, item: url }
    ]
  };
  const app = {
    '@context': 'https://schema.org', '@type': 'SoftwareApplication', name: reg.name, url,
    applicationCategory: 'UtilitiesApplication', applicationSubCategory: reg.tag,
    operatingSystem: 'Any (web browser)', featureList: reg.keywords || [],
    description: metaDescRaw,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
    datePublished: DATE, dateModified: DATE,
    author: { '@type': 'Organization', name: 'F9XR Development Team', url: 'https://f9xr.org/' },
    publisher: { '@type': 'Organization', name: 'Troolify', url: BASE + '/', logo: { '@type': 'ImageObject', url: BASE + '/assets/images/logo_nobg.webp', width: 1407, height: 768 } }
  };
  const article = {
    '@context': 'https://schema.org', '@type': 'Article', headline: titleRaw,
    description: metaDescRaw, image: BASE + '/assets/images/og-image.jpg',
    datePublished: DATE, dateModified: DATE, mainEntityOfPage: url,
    author: { '@type': 'Organization', name: 'F9XR Development Team', url: 'https://f9xr.org/' },
    publisher: { '@type': 'Organization', name: 'Troolify', url: BASE + '/', logo: { '@type': 'ImageObject', url: BASE + '/assets/images/logo_nobg.webp', width: 1407, height: 768 } }
  };
  const faq = { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: faqMain };
  return [breadcrumb, app, article, faq].map(o => '<script type="application/ld+json">' + JSON.stringify(o) + '</script>').join('');
}

function buildHead(reg, url, titleAttr, descAttr, ogDescAttr, styleContent, faqMain) {
  const titleRaw = decode(titleAttr);
  const metaDescRaw = decode(ogDescAttr);
  return '<!doctypehtml><html lang="en"><head><meta charset="UTF-8">' +
    '<meta name="viewport"content="width=device-width,initial-scale=1">' +
    '<title>' + titleAttr + '</title>' +
    '<meta name="description"content="' + descAttr + '">' +
    '<meta name="author"content="F9XR Development Team">' +
    '<meta name="robots"content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1">' +
    '<meta name="theme-color"content="#212529">' +
    '<link rel="canonical"href="' + url + '">' +
    '<meta property="og:site_name"content="Troolify">' +
    '<meta property="og:locale"content="en_US">' +
    '<meta property="og:title"content="' + titleAttr + '">' +
    '<meta property="og:description"content="' + ogDescAttr + '">' +
    '<meta property="og:type"content="article">' +
    '<meta property="og:url"content="' + url + '">' +
    '<meta property="og:image"content="' + BASE + '/assets/images/og-image.jpg">' +
    '<meta property="og:image:width"content="1200"><meta property="og:image:height"content="630">' +
    '<meta property="article:published_time"content="' + DATE + '">' +
    '<meta property="article:modified_time"content="' + DATE + '">' +
    '<meta property="article:section"content="' + CAT_NAME + '">' +
    '<meta property="article:tag"content="' + decode(reg.tag) + '">' +
    '<meta property="article:tag"content="' + CAT_NAME + '">' +
    '<meta name="twitter:card"content="summary_large_image">' +
    '<meta name="twitter:title"content="' + titleAttr + '">' +
    '<meta name="twitter:description"content="' + ogDescAttr + '">' +
    '<meta name="twitter:image"content="' + BASE + '/assets/images/og-image.jpg">' +
    buildJsonLd(reg, url, titleRaw, metaDescRaw, faqMain) +
    '<link rel="icon"type="image/webp"href="../../assets/images/favicon.webp">' +
    '<link rel="icon"type="image/x-icon"href="../../assets/images/favicon.ico">' +
    '<link rel="stylesheet"href="../../assets/css/jakarta.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/icons.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/tailwind.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/tool-shared.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/tool.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/site-shell.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/tool-page.min.css">' +
    '<link rel="preload"as="style"href="../../assets/css/seo-article.min.css">' +
    '<link rel="stylesheet"href="../../assets/css/seo-article.min.css"media="print"onload="this.media=&#39;all&#39;">' +
    '<noscript><link rel="stylesheet"href="../../assets/css/seo-article.min.css"></noscript>' +
    '<style>' + styleContent + '</style>' +
    '<script async src="https://www.googletagmanager.com/gtag/js?id=G-1D3C2DDCHV"></script>' +
    '<script>function gtag(){dataLayer.push(arguments)}window.dataLayer=window.dataLayer||[],gtag("js",new Date),gtag("config","G-1D3C2DDCHV");</script>' +
    '<meta name="google-adsense-account"content="ca-pub-9769892721842144">' +
    '<script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-9769892721842144"crossorigin="anonymous"></script>' +
    '<link rel="stylesheet"href="../../assets/css/view-transitions.min.css"></head>';
}

const dir = path.join(ROOT, 'tools', 'units');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.html') && f !== 'index.html');
let changed = 0;

for (const file of files) {
  const href = 'tools/units/' + file;
  const reg = REG[href];
  if (!reg) { console.log('SKIP (no registry entry): ' + file); continue; }
  const p = path.join(dir, file);
  const h = fs.readFileSync(p, 'utf8');
  const headEnd = h.indexOf('</head>');
  if (headEnd === -1) { console.log('SKIP (no </head>): ' + file); continue; }
  const oldHead = h.slice(0, headEnd + 7);
  const body = h.slice(headEnd + 7);

  const titleAttr = (oldHead.match(/<title>([\s\S]*?)<\/title>/) || [, ''])[1];
  const descAttr = (oldHead.match(/<meta name="description" ?content="([^"]*)">/) || [, ''])[1];
  const ogDescAttr = (oldHead.match(/<meta property="og:description" ?content="([^"]*)">/) || [, descAttr])[1];
  const url = (oldHead.match(/<link rel="canonical" ?href="([^"]+)"/) || [, BASE + '/' + href])[1];
  const styleContent = (oldHead.match(/<style>([\s\S]*?)<\/style>/) || [, ''])[1];
  if (!titleAttr || !descAttr || !url) { console.log('SKIP (missing fields): ' + file); continue; }

  let faqMain = [];
  const ldRe = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g;
  let lm;
  while ((lm = ldRe.exec(h))) {
    try {
      const o = JSON.parse(lm[1]);
      if (o && o['@type'] === 'FAQPage') { faqMain = o.mainEntity || []; break; }
    } catch (e) { /* ignore malformed */ }
  }
  if (!faqMain.length) { console.log('WARN no FAQ found for ' + file); }

  const newHead = buildHead(reg, url, titleAttr, descAttr, ogDescAttr, styleContent, faqMain);
  /* Fix the old gen-units body: it closed </div></main> prematurely, before the
     keyword/author/related/disclaimer/comments sections, then closed them a
     second time at the end (two </main>, one extra </div>). Removing the
     premature close keeps those sections inside main/container like every
     other generated tool page. */
  const fixedBody = body.replace(/<\/div><\/main>(?=<section class="keyword-box")/, '');
  fs.writeFileSync(p, newHead + fixedBody, 'utf8');
  changed++;
  console.log('upgraded ' + file + '  (ld=' + (faqMain.length) + ' faq, url=' + url + ')');
}
console.log('\nupgraded: ' + changed + '/' + files.length);
