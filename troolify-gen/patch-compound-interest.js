/* ============================================================================
   Troolify - Compound Interest Calculator upgrade
   ----------------------------------------------------------------------------
   Replaces the basic compound-interest widget on
   tools/finance/compound-interest-calculator.html with the full calculator
   (regular contributions with start/end timing, six currencies, inflation
   adjusted real value, year-by-year chart and table, step-by-step formula
   breakdown) and updates the page's meta + structured data to match.

   The page itself is generated by troolify-gen/gen-tools-batch14.js. This
   script upgrades that generated output in place, so run it once after the
   batch generator and keep the two in sync if either changes.

   It is NOT idempotent - it expects the original batch-14 markup (anchors
   such as the old <style> block and the "27 September 2026" date stamp).
   Restore tools/finance/compound-interest-calculator.html from git and re-run
   if you need to apply it again.

   Run:  node troolify-gen/patch-compound-interest.js   (from the repo root)
   ============================================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const F = path.join(ROOT, 'tools', 'finance', 'compound-interest-calculator.html');
const ASSETS = path.join(__dirname, 'compound-interest');

const css = fs.readFileSync(path.join(ASSETS, 'widget.css'), 'utf8').replace(/\r?\n/g, '\n');
const widget = fs.readFileSync(path.join(ASSETS, 'widget.html'), 'utf8').replace(/\r?\n/g, '\n');
const js = fs.readFileSync(path.join(ASSETS, 'widget.js'), 'utf8').replace(/\r?\n/g, '\n');

let h = fs.readFileSync(F, 'utf8');

function replaceOnce(label, from, to) {
  const i = h.indexOf(from);
  if (i < 0) throw new Error('anchor not found: ' + label);
  if (h.indexOf(from, i + 1) >= 0) throw new Error('anchor not unique: ' + label);
  h = h.slice(0, i) + to + h.slice(i + from.length);
  console.log('  replaced ' + label);
}

/* 1. the page <style> block -> the widget styles */
{
  const start = h.indexOf('<style>.calc-grid{');
  const end = h.indexOf('</style>', start);
  if (start < 0 || end < 0) throw new Error('style block not found');
  h = h.slice(0, start) + '<style>' + css + '</style>' + h.slice(end + '</style>'.length);
  console.log('  replaced <style> block');
}

/* 2. the old calculator panel -> the new widget (panel.clean shell kept so
      tool-page.js can still insert the workflow suggestions after it) */
{
  const start = h.indexOf('<div class="panel clean"><div class="panel-inner">');
  const marker = '<p class="proc-line"><i class="fa-solid fa-bolt"></i><span id="ciProc">Ready - calculations happen in this tab.</span></p>';
  const mEnd = h.indexOf(marker, start);
  if (start < 0 || mEnd < 0) throw new Error('panel not found');
  const end = h.indexOf('</div></div>', mEnd);
  if (end < 0) throw new Error('panel end not found');
  const to =
    '<div class="panel clean"><div class="panel-inner">' + widget +
    '<p class="proc-line"><i class="fa-solid fa-bolt"></i><span id="ciProc">Ready - calculations happen in this tab.</span></p>' +
    '</div></div>';
  h = h.slice(0, start) + to + h.slice(end + '</div></div>'.length);
  console.log('  replaced calculator panel');
}

/* 3. the inline script -> the widget script */
{
  const start = h.indexOf('<script>!function(){"use strict";var e=document.getElementById("ciPrincipal")');
  const end = h.indexOf('</script>', start);
  if (start < 0 || end < 0) throw new Error('inline script not found');
  h = h.slice(0, start) + '<script>' + js + '</script>' + h.slice(end + '</script>'.length);
  console.log('  replaced inline script');
}

/* 4. meta + structured data now describe the richer calculator */
replaceOnce(
  'meta description',
  '<meta name="description"content="Calculate compound interest, future value and interest earned for any principal, contribution and rate. Free and 100% client-side.">',
  '<meta name="description"content="Calculate compound interest with regular contributions, six currencies, inflation-adjusted real value, a year-by-year growth chart and a full formula breakdown. Free and 100% client-side.">'
);
replaceOnce(
  'og:description',
  '<meta property="og:description"content="Calculate compound interest, future value and interest earned for any principal, contribution and rate. Free, private and 100% client-side.">',
  '<meta property="og:description"content="Calculate compound interest with regular contributions, inflation-adjusted real value, a growth chart and a full formula breakdown. Free, private and 100% client-side.">'
);
replaceOnce(
  'twitter:description',
  '<meta name="twitter:description"content="Calculate compound interest, future value and interest earned for any principal, contribution and rate - 100% browser based.">',
  '<meta name="twitter:description"content="Calculate compound interest with regular contributions, inflation-adjusted real value, a growth chart and a formula breakdown - 100% browser based.">'
);
replaceOnce(
  'software featureList',
  '"featureList":["Calculate future value","Show interest earned","Support monthly contributions","Compounding frequency","100% client-side processing"]',
  '"featureList":["Calculate future value","Show interest earned","Regular contributions with start or end of period timing","Six currencies","Inflation-adjusted real value","Year-by-year growth chart","Step-by-step formula breakdown","100% client-side processing"]'
);
/* The description string appears in both the SoftwareApplication and the
   Article blocks, so anchor on the key that follows it to stay unique. */
replaceOnce(
  'software description',
  '"description":"Calculate compound interest, future value and interest earned for any principal, contribution and rate. Free online compound interest calculator - 100% client-side.","offers":{"@type":"Offer"',
  '"description":"Calculate compound interest with regular contributions, six currencies, inflation-adjusted real value, a growth chart and a full formula breakdown. Free online compound interest calculator - 100% client-side.","offers":{"@type":"Offer"'
);
replaceOnce(
  'article description',
  '"description":"Calculate compound interest, future value and interest earned for any principal, contribution and rate. Free online compound interest calculator - 100% client-side.","image"',
  '"description":"Calculate compound interest with regular contributions, six currencies, inflation-adjusted real value, a growth chart and a full formula breakdown. Free online compound interest calculator - 100% client-side.","image"'
);
replaceOnce(
  'dateModified (software)',
  '"offers":{"@type":"Offer","price":"0","priceCurrency":"USD"},"datePublished":"2026-09-27","dateModified":"2026-09-27"',
  '"offers":{"@type":"Offer","price":"0","priceCurrency":"USD"},"datePublished":"2026-09-27","dateModified":"2026-10-22"'
);
replaceOnce(
  'dateModified (article)',
  '"datePublished":"2026-09-27","dateModified":"2026-09-27","mainEntityOfPage"',
  '"datePublished":"2026-09-27","dateModified":"2026-10-22","mainEntityOfPage"'
);
replaceOnce(
  'article:modified_time',
  '<meta property="article:modified_time"content="2026-09-27">',
  '<meta property="article:modified_time"content="2026-10-22">'
);
replaceOnce(
  'hero last updated',
  '<span class="detail-value">27 September 2026</span>',
  '<span class="detail-value">22 October 2026</span>'
);
replaceOnce(
  'hero intro',
  '<p>See how your money grows with the power of compounding. Enter a principal, optional monthly contributions and an interest rate to instantly find the future value and total interest earned.</p>',
  '<p>See how your money grows with the power of compounding. Enter a principal, regular contributions, an interest rate and an inflation rate to instantly find the future value, the interest earned and what it is worth in today&#39;s money - with a year-by-year chart and a step-by-step breakdown of every formula we used.</p>'
);
replaceOnce(
  'how-to steps',
  '"step":[{"@type":"HowToStep","position":1,"text":"Enter your initial principal - the amount you are starting with."},{"@type":"HowToStep","position":2,"text":"Add the annual interest rate and how many years you plan to save or invest."},{"@type":"HowToStep","position":3,"text":"Optionally add a monthly contribution to see the effect of regular saving."},{"@type":"HowToStep","position":4,"text":"Choose a compounding frequency (monthly is common and realistic for most accounts)."}]',
  '"step":[{"@type":"HowToStep","position":1,"text":"Enter your initial principal - the amount you are starting with - and pick your currency."},{"@type":"HowToStep","position":2,"text":"Add the annual interest rate and how many years you plan to save or invest."},{"@type":"HowToStep","position":3,"text":"Optionally add a regular contribution, choose how often it is added and whether it lands at the start or end of each period."},{"@type":"HowToStep","position":4,"text":"Choose a compounding frequency (monthly is common and realistic for most accounts)."},{"@type":"HowToStep","position":5,"text":"Add an inflation rate to see the future amount expressed in today&#39;s money."}]'
);
replaceOnce(
  'article how-to list',
  '<ol><li><strong>Enter your initial principal</strong> - the amount you are starting with.</li><li><strong>Add the annual interest rate</strong> and how many years you plan to save or invest.</li><li><strong>Optionally add a monthly contribution</strong> to see the effect of regular saving.</li><li><strong>Choose a compounding frequency</strong> (monthly is common and realistic for most accounts).</li></ol>',
  '<ol><li><strong>Enter your initial principal</strong> - the amount you are starting with - and pick your currency.</li><li><strong>Add the annual interest rate</strong> and how many years you plan to save or invest.</li><li><strong>Optionally add a regular contribution</strong>, choose how often it is added, and say whether it lands at the start or the end of each period.</li><li><strong>Choose a compounding frequency</strong> (monthly is common and realistic for most accounts).</li><li><strong>Add an inflation rate</strong> to see what the future amount is worth in today&#39;s money.</li></ol>'
);
replaceOnce(
  'article result sentence',
  '<p>The result shows your future value, total contributed, and the interest earned on top.</p>',
  '<p>The result shows your future value, total contributed, the interest earned on top, and the inflation-adjusted value in today&#39;s money - plus a year-by-year chart, table and a step-by-step explanation of every formula behind the numbers.</p>'
);

fs.writeFileSync(F, h, 'utf8');
console.log('\nwritten: ' + path.relative(ROOT, F) + ' (' + h.length + ' bytes)');
